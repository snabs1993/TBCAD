"""Thai part of the TBCAD single-stroke font (original design, MIT).

Base letters live in a box x 0..8 (shifted by 1.5 into an advance of 11), y 0..10; ascender
letters rise to 14, descender letters fall to -4. Marks have zero advance and are drawn centred on
x = 0; the shaper centres them over the previous base glyph. Upper vowels sit at y 10.8..12.4, tone
marks at 13..15 (the shaper drops a tone mark that has no upper vowel under it by `tonedrop`).
"""
import math


def arc(cx, cy, rx, ry, a0, a1, n=None):
    n = n or max(4, int(abs(a1 - a0) / 15))
    return [(round(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)), 2),
             round(cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n)), 2)) for i in range(n + 1)]


def add_thai(G):
    def sh(strokes, dx=1.5):
        return [[(round(x + dx, 2), round(y, 2)) for x, y in st] for st in strokes]

    def T(cp, *strokes, adv=11):
        G[cp] = (adv, None, sh(strokes))

    def M(cp, kind, *strokes):
        G[cp] = (0, kind, [list(st) for st in strokes])

    def oval(cx, cy, rx, ry):
        return arc(cx, cy, rx, ry, 90, 450, 20)

    def loop(x=1.8, y=8.2, r=1.3):
        return oval(x, y, r, r)

    def arch(y0=6.5, x0=0, x1=8):
        return arc((x0 + x1) / 2, y0, (x1 - x0) / 2, 10 - y0, 180, 0)

    def cup(y0, x0=0, x1=8):
        return arc((x0 + x1) / 2, y0, (x1 - x0) / 2, y0, 180, 360)

    # Reusable shapes -----------------------------------------------------------------------
    n_shape = [(0, 0), (0, 6.5)] + arch(6.5) + [(8, 0)]                 # ก-like
    tall_n = arc(4, 5, 4, 5, 180, 0)                                    # arch from y=5
    u_box = [(0, 10), (0, 0), (8, 0), (8, 10)]                         # บ-like box
    ukh = [(0, 10), (0, 3)] + arc(3, 3, 3, 3, 180, 360) + [(6, 10)]    # ข-like
    ay = [(0, 5.5)] + arc(4, 5.5, 4, 4.5, 180, 0) + [(8, 0)]
    foot = [(4, 0), (4, -4)]
    base = [(2, -4), (6, -4)]

    T(0xE01, n_shape, loop())                                           # ก
    T(0xE02, ukh, loop())                                               # ข
    T(0xE03, ukh, loop(), [(6, 4), (8, 4)])                             # ฃ
    T(0xE04, [(8, 0), (8, 10)], arc(4.5, 5, 3.5, 4, 90, 360))           # ค
    T(0xE05, [(8, 0), (8, 10), (6.5, 12)], arc(4.5, 5, 3.5, 4, 90, 360))  # ฅ
    T(0xE06, [(0, 0), (0, 10)], [(0, 6)] + arc(4, 6, 4, 4, 180, 0) + [(8, 0)], [(4, 6), (4, 0)])  # ฆ
    T(0xE07, [(0, 4), (0, 6.5)] + arch(6.5) + [(8, 3)] + arc(5.5, 3, 2.5, 2.5, 0, -180), loop())  # ง
    T(0xE08, [(2, 0), (0, 2), (0, 5.5)] + arc(4, 5.5, 4, 4.5, 180, 0) + [(8, 0), (2, 0)])  # จ
    T(0xE09, [(0, 0), (0, 10)], tall_n + [(8, 0)], [(2.5, 3), (5.5, 3)])  # ฉ
    T(0xE0A, [(0, 10), (0, 0)], tall_n + [(8, 0)], loop())              # ช
    T(0xE0B, [(0, 0), (0, 10)], tall_n + [(8, 0)], [(8, 5), (6, 3)])    # ซ
    T(0xE0C, [(0, 10), (0, 0)], tall_n + [(8, 0), (6, -2.5)], loop())   # ฌ
    T(0xE0D, [(0, 10), (0, -4)], arc(4, 6, 4, 4, 180, 0) + [(8, 0)], loop(1.8, 8.4))  # ญ
    T(0xE0E, [(0, 10), (0, 0)], ay, foot, base)                         # ฎ
    T(0xE0F, n_shape, loop(), foot, base)                               # ฏ
    T(0xE10, ukh, foot, base)                                           # ฐ
    T(0xE11, [(0, 10), (0, 3.5)] + arc(4, 3.5, 4, 3.5, 180, 360) + [(8, 10), (6, 10)])  # ฑ
    T(0xE12, [(0, 10), (0, 3.5)] + arc(4, 3.5, 4, 3.5, 180, 360) + [(8, 10), (6, 10)], loop())  # ฒ
    T(0xE13, n_shape[:-1] + [(8, -3), (6, -4)], loop())                 # ณ
    T(0xE14, loop(), [(8, 0), (8, 6.5)] + arc(4, 6.5, 4, 3.5, 0, 180) + [(0, 2.5), (2, 0.5), (4, 0.3)])  # ด
    T(0xE15, n_shape, loop(), [(4, 6.5), (4, 3)])                       # ต
    T(0xE16, [(8, 0), (8, 6.5)] + arc(4, 6.5, 4, 3.5, 0, 180) + [(0, 2.5), (1, 0.8), (4, 0)], [(4, 6.5), (4, 3)])  # ถ
    T(0xE17, [(0, 10), (0, 0)], tall_n + [(8, 0)], loop(), [(0, 2), (3, 2)])  # ท
    T(0xE18, [(0, 10), (0, 0)], tall_n + [(8, 0)], [(0, 2), (3, 2)])    # ธ
    T(0xE19, n_shape, loop(), )                    # น
    T(0xE1A, u_box)                                                     # บ
    T(0xE1B, [(0, 10), (0, 0), (8, 0), (8, 14)])                        # ป (tall on the right)
    T(0xE1C, u_box, [(0, 6), (3, 6)])                                   # ผ
    T(0xE1D, [(0, 10), (0, 0), (8, 0), (8, 14)], [(0, 6), (3, 6)])      # ฝ
    T(0xE1E, u_box, loop(4, 6.5, 1.2))                                  # พ
    T(0xE1F, [(0, 10), (0, 0), (8, 0), (8, 14)], loop(4, 6.5, 1.2))     # ฟ
    T(0xE20, [(0, 0), (0, 10)], tall_n + [(8, 0)], [(4, 5), (4, 0)])    # ภ
    T(0xE21, [(0, 0), (0, 10), (8, 10), (8, 0)], loop(4, 3.5, 1.3))     # ม
    T(0xE22, ukh[:-1] + [(6, 5), (8, 5), (8, 0)])                       # ย
    T(0xE23, [(0, 0), (0, 6.5)] + arc(3.5, 6.5, 3.5, 3.5, 180, 40), loop())  # ร
    T(0xE24, [(0, 0), (0, 6.5)] + arc(3, 6.5, 3, 3.5, 180, 0) + [(6, 0)], loop())  # ฤ
    T(0xE25, [(0, 0), (0, 10)], tall_n + [(8, 0)], loop(4, 2.5, 1.2))   # ล
    T(0xE26, [(0, 0), (0, 6.5)] + arc(3, 6.5, 3, 3.5, 180, 0) + [(6, 0)], loop(), [(0, 3), (6, 3)])  # ฦ
    T(0xE27, [(0, 10), (0, 3)] + arc(3.5, 3, 3.5, 3, 180, 360) + [(7, 10)])  # ว
    T(0xE28, [(0, 10), (0, 0)], [(0, 6)] + arc(4, 6, 4, 4, 180, 0) + [(8, 0)], [(0, 3), (4, 3)])  # ศ
    T(0xE29, [(0, 10), (0, 0)], [(0, 6)] + arc(4, 6, 4, 4, 180, 0) + [(8, 0)], [(0, 3), (4, 3)], [(8, 6), (9.5, 8)])  # ษ
    T(0xE2A, [(0, 0), (0, 10)], [(0, 7)] + arc(4, 7, 4, 3, 180, 0) + [(8, 0)], loop(2.2, 2.4, 1.4))  # ส
    T(0xE2B, [(0, 10), (0, 0), (2.5, 4)], tall_n + [(8, 0)])            # ห (no ascender)
    T(0xE2C, [(0, 10), (0, 0), (2.5, 4)], tall_n + [(8, 0)], [(8, 5), (8, 14)])  # ฬ (tall right)
    T(0xE2D, oval(4, 5, 3.4, 5), adv=10)                                 # อ
    T(0xE2E, oval(3.5, 5, 3.5, 5), [(7, 0), (7, 10)], adv=10)            # ฮ
    # Vowels and signs --------------------------------------------------------------------
    G[0xE2F] = (7, None, [[(1, 10), (1, 0)], [(1, 10), (5.5, 10), (5.5, 7.5), (1, 7.5)]])  # ฯ
    G[0xE30] = (6, None, [oval(2.5, 7.8, 1.2, 1.2), oval(2.5, 2.4, 1.2, 1.2)])             # ะ
    aa = [(0.5, 7.5)] + arc(2.5, 7.5, 2, 2.5, 180, 0) + [(4.5, 0)]
    G[0xE32] = (7, None, [aa])                                                              # า
    G[0xE33] = (10, None, [[(x + 0, y) for x, y in aa], oval(1.0, 11.8, 0.9, 0.9)])         # ำ
    M(0xE31, "upper", [(-2.2, 10.8), (-1.2, 12.4), (1, 12.4), (2.2, 11.4)])                # ั
    M(0xE34, "upper", arc(0, 10.8, 2.3, 1.5, 180, 0))                                       # ิ
    M(0xE35, "upper", arc(0, 10.8, 2.3, 1.5, 180, 0), [(2.3, 10.8), (2.3, 13.0)])          # ี
    M(0xE36, "upper", arc(0, 10.8, 2.3, 1.5, 180, 0), [(2.3, 10.8), (2.3, 12.2)], [(0.3, 12.2), (0.3, 12.5)])  # ึ
    M(0xE37, "upper", arc(0, 10.8, 2.3, 1.5, 180, 0), [(2.3, 10.8), (2.3, 12.2)], oval(0.3, 12.6, 0.4, 0.4))  # ื
    M(0xE38, "lower", [(0, -0.8), (0, -2.8), (1.3, -2.8)])                                  # ุ
    M(0xE39, "lower", [(0, -0.8), (0, -2.8), (1.3, -2.8)], [(-1.4, -3.4), (1.3, -3.4)])     # ู
    M(0xE3A, "lower", oval(0, -1.8, 0.5, 0.5))                                              # ฺ
    G[0xE40] = (6, None, [[(1, 0), (1, 8.5)] + arc(2.5, 8.5, 1.5, 1.5, 180, 60)])           # เ
    G[0xE41] = (10, None, [[(1, 0), (1, 8.5)] + arc(2.5, 8.5, 1.5, 1.5, 180, 60),
                          [(5, 0), (5, 8.5)] + arc(6.5, 8.5, 1.5, 1.5, 180, 60)])          # แ
    G[0xE42] = (7, None, [[(1, 0), (1, 12), (4.5, 12)]])                                    # โ
    G[0xE43] = (7, None, [[(1, 0), (1, 10)], oval(3.0, 11.3, 1.5, 1.5)])                    # ใ
    G[0xE44] = (7, None, [[(1, 0), (1, 10), (4, 12.5)]])                                    # ไ
    G[0xE45] = (7, None, [[(1, 10), (1, 3)] + arc(3, 3, 2, 3, 180, 360)])                   # ๅ
    G[0xE46] = (10, None, [[(0, 7.5), (2.5, 7.5), (2.5, 0)], [(4.5, 7.5), (7, 7.5), (7, 0)]])  # ๆ
    M(0xE47, "upper", [(-1.8, 11.2), (-0.8, 12.6), (0.6, 11.4), (1.8, 12.6)])               # ็
    M(0xE48, "tone", [(0, 13.2), (0, 14.8)])                                                # ่
    M(0xE49, "tone", [(-1.2, 14.8), (-1.2, 13.2), (0.6, 13.2), (0.6, 14.6), (-0.4, 14.6)])  # ้
    M(0xE4A, "tone", [(-1.3, 14.0), (1.3, 14.0)], [(0, 13.0), (0, 15.0)])                   # ๊
    M(0xE4B, "tone", [(-1.4, 13.2), (1.4, 13.2), (0, 14.9), (-1.4, 13.2)])                  # ๋
    M(0xE4C, "tone", [(-1.6, 13.2), (0, 14.9), (1.6, 13.2)])   # ์
    M(0xE4D, "upper", oval(0, 11.8, 0.9, 0.9))                                              # ํ
    M(0xE4E, "upper", [(-1.5, 11.0), (0, 13.0), (1.5, 11.0)])                               # ๎
    G[0xE4F] = (11, None, [oval(4, 5, 3.2, 3.2), oval(4, 5, 1.2, 1.2)])                      # ๏
    G[0xE5A] = (14, None, [oval(2.5, 5, 2, 2), oval(8.5, 5, 2, 2), [(4.5, 5), (6.5, 5)]])    # ๚
    G[0xE5B] = (14, None, [oval(5, 5, 4, 4), oval(5, 5, 1.4, 1.4)])                          # ๛
    G[0xE3F] = (11, None, [[(1.5, 0), (1.5, 10), (6, 10)] + arc(6, 7.5, 2.5, 2.5, 90, -90) + [(1.5, 5)],
                          [(1.5, 5), (6.8, 5)] + arc(6.8, 2.5, 2.5, 2.5, 90, -90) + [(1.5, 0)],
                          [(4, 12.5), (4, -2.5)]])                                           # ฿
    # Thai digits ---------------------------------------------------------------------------
    def d(cp, *st):
        G[cp] = (11, None, sh(st))

    d(0xE50, oval(4, 5, 3.4, 5), oval(4, 5, 1.2, 1.5))                                       # ๐
    d(0xE51, [(1, 10), (1, 2)] + arc(3.5, 2, 2.5, 2, 180, 360) + [(6, 6)], oval(4.5, 7.5, 1.3, 1.3))  # ๑
    d(0xE52, [(0, 10), (0, 4)] + arc(3, 4, 3, 4, 180, 360))  # ๒
    d(0xE53, [(0, 10), (0, 2)] + arc(3.5, 2, 3.5, 2, 180, 360) + [(7, 10)])               # ๓
    d(0xE54, [(0, 10), (0, 0), (7, 0), (7, 10)], [(3.5, 0), (3.5, 7)])                     # ๔
    d(0xE55, [(0, 10), (0, 0), (7, 0), (7, 5)] + arc(4.5, 5, 2.5, 4.5, 0, 180))            # ๕
    d(0xE56, [(1, 10), (1, 3)] + arc(3.5, 3, 2.5, 3, 180, 360))  # ๖
    d(0xE57, ukh[:-1] + [(6, 10)], [(3, 3), (3, 7)])                                         # ๗
    d(0xE58, [(0, 10), (0, 3)] + arc(3, 3, 3, 3, 180, 360) + [(6, 10)], loop(3, 6.5, 1.1))  # ๘
    d(0xE59, oval(3.5, 6.5, 3, 3.5), [(6.5, 6.5), (6, 0)])                                    # ๙
