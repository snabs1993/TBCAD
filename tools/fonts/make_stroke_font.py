def arc(cx, cy, rx, ry, a0, a1, n=None):
    """Elliptic arc, degrees, counter-clockwise from a0 to a1."""
    n = n or max(4, int(abs(a1 - a0) / 15))
    return [(round(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)), 2),
             round(cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n)), 2))
            for i in range(n + 1)]


def oval(cx, cy, rx, ry):
    return arc(cx, cy, rx, ry, 90, 450, 24)


