def tbsf(extra=None):
    out = ["# TBCAD single-stroke font. Generated by tools/fonts/make_stroke_font.py.",
           "# Original work of the TBCAD contributors, MIT license.",
           "tbsf 1", "family TBCAD Stroke", f"upm {UPM}", f"cap {CAP}", f"xheight {XH}",
           f"ascender {ASC}", f"descender {DESC}", "tonedrop 1"]
    for cp in sorted(G):
        adv, mark, strokes = G[cp]
        out.append(f"glyph {cp:X} {adv}" + (f" mark={mark}" if mark else ""))
        for s in strokes:
            out.append("s " + " ".join(f"{x:g} {y:g}" for x, y in s))
    return "\n".join(out) + "\n"


def svg():
    x = 0
    y = 0
    parts = []
    for i, cp in enumerate(sorted(G)):
        adv, mark, strokes = G[cp]
        if i % 16 == 0 and i:
            y += 30
            x = 0
        for s in strokes:
            pts = " ".join(f"{x + px:.2f},{y + 20 - py:.2f}" for px, py in s)
            parts.append(f'<polyline points="{pts}" fill="none" stroke="black" stroke-width="0.7" stroke-linecap="round"/>')
        x += adv + 4
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="-5 -5 330 {y + 40}" width="1320" height="{(y + 40) * 4}"><rect x="-5" y="-5" width="400" height="{y+50}" fill="white"/>' + "".join(parts) + "</svg>"


