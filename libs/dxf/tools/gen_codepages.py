#!/usr/bin/env python3
"""Generates libs/dxf/src/encoding/tables/cp*.cpp (codepage -> Unicode tables).

Source of the mapping data, in order of preference:
  1. --mapping-dir DIR: the Unicode Consortium vendor mapping files
     (https://unicode.org/Public/MAPPINGS/VENDORS/MICSFT/WINDOWS/CP874.TXT ...).
  2. Python's built-in codecs (their tables derive from the same files). Used when no
     directory is given, so the generator also works offline.

The output only depends on the mapping data, so both sources give identical files for
the codepages listed here. Written by the TBCAD project, MIT licensed. No third-party
code is used.

Usage: gen_codepages.py [--mapping-dir DIR] [--out DIR]
"""
import argparse
import os
import sys

SINGLE = [874, 1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258]
DOUBLE = [932, 936, 949, 950]
UNDEFINED = 0xFFFD
LEAD = 0xFFFF  # marker in the single-byte part: this byte starts a two-byte sequence


def parse_mapping_file(path):
    """Returns (single: dict byte->cp, double: dict (lead,trail)->cp, leads: set)."""
    single, double, leads = {}, {}, set()
    with open(path, encoding="ascii", errors="replace") as f:
        for raw in f:
            line = raw.split("#", 1)
            comment = line[1].strip().upper() if len(line) > 1 else ""
            toks = line[0].split()
            if not toks or not toks[0].lower().startswith("0x"):
                continue
            code = int(toks[0], 16)
            if len(toks) < 2:
                if "LEAD BYTE" in comment:
                    leads.add(code)
                continue
            uni = int(toks[1], 16)
            if code > 0xFF:
                double[(code >> 8, code & 0xFF)] = uni
            else:
                single[code] = uni
    return single, double, leads


def from_python(cp):
    single, double, leads = {}, {}, set()
    name = f"cp{cp}"
    for b in range(256):
        try:
            single[b] = ord(bytes([b]).decode(name))
            continue
        except UnicodeDecodeError:
            pass
        if b >= 0x80:
            ok = False
            for t in range(256):
                try:
                    s = bytes([b, t]).decode(name)
                except UnicodeDecodeError:
                    continue
                if len(s) == 1:
                    double[(b, t)] = ord(s)
                    ok = True
            if ok:
                leads.add(b)
    return single, double, leads


def emit(cp, single, double, leads, out_dir):
    hi = []
    for b in range(0x80, 0x100):
        if b in leads:
            hi.append(LEAD)
        else:
            u = single.get(b, UNDEFINED)
            if u > 0xFFFF:
                u = UNDEFINED
            hi.append(u)
    lines = []
    w = lines.append
    w("// Generated by libs/dxf/tools/gen_codepages.py. Do not edit.")
    w(f"// Codepage {cp} -> Unicode.")
    w("// clang-format off")
    w('#include "codepage.h"')
    w("")
    w("namespace tbcad::dxf::detail {")
    w("")
    if cp in SINGLE:
        w(f"const SingleByteTable kCp{cp} = {{{{")
        for i in range(0, 128, 8):
            w("    " + ", ".join(f"0x{v:04X}" for v in hi[i:i + 8]) + ",")
        w("}};")
    else:
        lmin = min(l for l, _ in double)
        lmax = max(l for l, _ in double)
        tmin = min(t for _, t in double)
        tmax = max(t for _, t in double)
        tw = tmax - tmin + 1
        w(f"static const char16_t kCp{cp}Pairs[] = {{")
        row = []
        for l in range(lmin, lmax + 1):
            for t in range(tmin, tmax + 1):
                u = double.get((l, t), 0)
                row.append(f"0x{u:X}")
        for i in range(0, len(row), 16):
            w("    " + ",".join(row[i:i + 16]) + ",")
        w("};")
        w("")
        w(f"const DoubleByteTable kCp{cp} = {{")
        w("    {")
        for i in range(0, 128, 8):
            w("        " + ", ".join(f"0x{v:04X}" for v in hi[i:i + 8]) + ",")
        w("    },")
        w(f"    0x{lmin:02X}, 0x{lmax:02X}, 0x{tmin:02X}, 0x{tmax:02X}, kCp{cp}Pairs}};")
        _ = tw
    w("")
    w("}  // namespace tbcad::dxf::detail")
    w("// clang-format on")
    path = os.path.join(out_dir, f"cp{cp}.cpp")
    with open(path, "w", newline="\n", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mapping-dir")
    ap.add_argument("--out", default=os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "..", "src", "encoding", "tables"))
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    for cp in SINGLE + DOUBLE:
        if args.mapping_dir:
            p = os.path.join(args.mapping_dir, f"CP{cp}.TXT")
            single, double, leads = parse_mapping_file(p)
        else:
            single, double, leads = from_python(cp)
        print(emit(cp, single, double, leads, args.out), file=sys.stderr)


if __name__ == "__main__":
    main()
