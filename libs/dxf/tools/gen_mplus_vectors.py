#!/usr/bin/env python3
"""Writes tests/corpus/encoding/mplus_vectors.txt: sample \\M+nXXXX escapes with the character each
must decode to, computed with Python's codecs (shift_jis/big5/cp949/johab/gbk). The C++ test
decodeText: \\M+ vectors checks the digit -> codepage mapping and the tables against it.

n: 1 Shift-JIS (932), 2 Big5 (950), 3 KS C 5601 (949), 4 Johab (1361), 5 GB2312/GBK (936).
Line format: <n> <4 hex digits> <U+codepoint>. Written by the TBCAD project, MIT licensed.
"""
import os

CODECS = {1: "cp932", 2: "cp950", 3: "cp949", 4: "johab", 5: "cp936"}
STEP = 37  # a deterministic spread over every codepage, ~200 vectors each


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..",
                       "tests", "corpus", "encoding", "mplus_vectors.txt")
    lines = ["# \\M+n escape vectors, generated by libs/dxf/tools/gen_mplus_vectors.py"]
    for n, codec in CODECS.items():
        found = []
        for lead in range(0x81, 0xFF):
            for trail in range(0x30, 0xFF):
                try:
                    s = bytes([lead, trail]).decode(codec)
                except UnicodeDecodeError:
                    continue
                if len(s) == 1 and ord(s) > 0x7F:
                    found.append((lead, trail, ord(s)))
        for lead, trail, u in found[::STEP]:
            lines.append(f"{n} {lead:02X}{trail:02X} U+{u:04X}")
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(out, len(lines) - 1, "vectors")


if __name__ == "__main__":
    main()
